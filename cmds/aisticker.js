/**
 * cmds/aisticker.js
 *
 * .aisticker / .ais / .aistick (reply to image/video/sticker)
 *
 * WhatsApp's Native "Meta AI Sticker" format with prompt & AI badge metadata.
 */

const sharp = require('sharp');
const { downloadMediaMessage } = require('@whiskeysockets/baileys');
// Blank-sticker fix: valid WebP EXIF (VP8X + padding) + ≤900KB animated WebP.
const { addStickerExif, videoToAnimatedWebp } = require('../lib/stickerUtil');

/**
 * Image or existing-sticker buffer -> AI-look enhanced 512x512 WebP.
 */
async function imageToAiSticker(buffer) {
  return sharp(buffer, { animated: false })
    .resize(512, 512, {
      fit: 'contain',
      background: { r: 255, g: 255, b: 255, alpha: 0 },
    })
    .sharpen()
    .normalize()
    .webp({ quality: 100 })
    .toBuffer();
}

/**
 * Meta AI Sticker EXIF metadata (JSON). 'is-ai-sticker' aur 'ai-prompt' tags.
 * Isko WebP me `addStickerExif` (lib/stickerUtil.js) inject karta hai.
 */
function metaAiExifJson(packname, author, promptText = 'AI Generated Sticker') {
  return {
    'sticker-pack-id': `meta-ai-${Date.now()}`,
    'sticker-pack-name': packname,
    'sticker-pack-publisher': author,
    'is-ai-sticker': 1,
    'ai-prompt': promptText,
    'is-avatar-sticker': 0,
    emojis: ['✨', '🤖'],
  };
}

module.exports = {
  command: ['aisticker', 'ais', 'aistick'],
  description: 'Convert media to native Meta AI Sticker format.',

  run: async ({ sock, jid, msg }) => {
    try {
      const quotedInfo = msg.message?.extendedTextMessage?.contextInfo;
      const quotedMessage = quotedInfo?.quotedMessage;

      if (!quotedMessage) {
        await sock.sendMessage(
          jid,
          {
            text: '❗ 𝖴sᴀɢᴇ :\n𝖱ᴇᴘʟʏ ᴛᴏ ᴀɴ ɪᴍᴀɢᴇ / ᴠɪᴅᴇᴏ / sᴛɪᴄᴋᴇʀ\n\n.𝖆𝖎𝖘𝖙𝖎𝖈𝖐𝖊𝖗',
          },
          { quoted: msg }
        );
        return;
      }

      const mediaType = quotedMessage.imageMessage
        ? 'image'
        : quotedMessage.videoMessage
        ? 'video'
        : quotedMessage.stickerMessage
        ? 'sticker'
        : null;

      if (!mediaType) {
        await sock.sendMessage(
          jid,
          { text: '❌ ᴘʟᴇᴀsᴇ ʀᴇᴘʟʏ ᴛᴏ ᴀɴ ɪᴍᴀɢᴇ, ᴠɪᴅᴇᴏ ᴏʀ sᴛɪᴄᴋᴇʀ ᴏɴʟʏ.' },
          { quoted: msg }
        );
        return;
      }

      await sock.sendMessage(jid, { react: { text: '✨', key: msg.key } }).catch(() => {});

      const fakeMsg = {
        key: {
          remoteJid: jid,
          fromMe: false,
          id: quotedInfo.stanzaId,
          participant: quotedInfo.participant,
        },
        message: quotedMessage,
      };

      const buffer = await downloadMediaMessage(fakeMsg, 'buffer', {});
      if (!buffer) {
        await sock.sendMessage(jid, { text: '❌ ғᴀɪʟᴇᴅ ᴛᴏ ᴅᴏᴡɴʟᴏᴀᴅ ᴍᴇᴅɪᴀ.' }, { quoted: msg });
        return;
      }

      let stickerBuffer =
        mediaType === 'video'
          ? await videoToAnimatedWebp(buffer, 'ais')
          : await imageToAiSticker(buffer);

      // Inject Meta AI specific EXIF tags
      stickerBuffer = addStickerExif(
        stickerBuffer,
        metaAiExifJson('Meta AI', global.botname || 'ʙᴜɴɴʏ-xᴍᴅ', 'AI generated custom sticker')
      );

      const senderJid = msg.key.participant || msg.key.remoteJid || sock.user.id;
      let senderDpUrl = 'https://i.ibb.co/L5hY0vw/black-dp.jpg';
      try {
        senderDpUrl = await sock.profilePictureUrl(senderJid, 'image');
      } catch (e) {}

      const vcard =
        `BEGIN:VCARD\n` +
        `VERSION:3.0\n` +
        `FN:Meta AI;\n` +
        `ORG:Meta AI Stickers;\n` +
        `TEL;type=CELL;type=VOICE;waid=13135550002:13135550002\n` +
        `END:VCARD`;

      const vcardReply = {
        key: {
          fromMe: false,
          participant: '13135550002@s.whatsapp.net',
          remoteJid: 'status@broadcast',
        },
        message: {
          eventMessage: {
            isCanceled: false,
            name: 'ʙᴜɴɴʏ -xᴍᴅ',
            description: vcard,
            location: {
              degreesLatitude: 0,
              degreesLongitude: 0,
              name: 'Meta AI',
            },
            startTime: Math.floor(Date.now() / 1000),
            extraGuestsAllowed: true,
            contextInfo: {
              externalAdReply: {
                title: 'Meta AI Sticker Generator',
                body: 'Generated by Meta AI',
                mediaType: 1,
                renderLargerThumbnail: false,
                thumbnailUrl: senderDpUrl,
                sourceUrl: 'https://wa.me/13135550002',
                showAdAttribution: true,
              },
            },
          },
        },
      };

      await sock.sendMessage(jid, { sticker: stickerBuffer }, { quoted: vcardReply });
      await sock.sendMessage(jid, { react: { text: '✅', key: msg.key } }).catch(() => {});
    } catch (err) {
      console.error('[.aisticker] error:', err);
      await sock.sendMessage(jid, { react: { text: '❌', key: msg.key } }).catch(() => {});
      await sock.sendMessage(
        jid,
        { text: `❌ Aɪ Sᴛɪᴄᴋᴇʀ ᴇʀʀᴏʀ:\n${err.message}` },
        { quoted: msg }
      );
    }
  },
};
